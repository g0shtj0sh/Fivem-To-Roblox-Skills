def rgb(index: int, default=(0.8, 0.8, 0.8)) -> list[float]:
    entry = PALETTE.get(int(index))
    if not entry:
        return list(default)
    h = entry[1].lstrip("#")
    return [round(int(h[i:i + 2], 16) / 255.0, 4) for i in (0, 2, 4)]



